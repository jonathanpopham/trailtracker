//! Generated-code classifier for the codebase brief.
//!
//! On real-world repos (evidenced on a 527-file .NET solution) the brief's
//! "largest units" and "highest fan-out" tables are dominated by machine
//! generated code: EF Core migration designers, protoc/gRPC output, XAML
//! codegen, and the like. This module classifies files as generated so the
//! brief can exclude or segregate them from the architecture signal.
//!
//! Detection is deterministic and std-only, and deliberately conservative:
//! a file is flagged only on well-known generated-file path conventions or
//! explicit generated-code markers in the head of its content. Hand-written
//! files should never be flagged (precision over recall).

/// Path suffixes (matched case-insensitively against the normalized path)
/// that mark a file as generated regardless of content.
const GENERATED_SUFFIXES: &[&str] = &[
    ".designer.cs", // WinForms/EF Core designer codegen
    ".g.cs",        // XAML / source-generator output
    ".g.i.cs",      // XAML intellisense stubs
    ".generated.cs",
    ".feature.cs", // SpecFlow codegen
    "grpc.cs",     // protoc gRPC service stubs (e.g. BasketGrpc.cs)
    ".pb.cs",      // protoc message output
    ".pb.go",
    "_pb2.py",
];

/// File names (the final path component, matched case-insensitively) that
/// mark a file as generated.
const GENERATED_FILENAMES: &[&str] = &["assemblyinfo.cs"];

/// Directory segments (matched case-insensitively, slash-delimited) whose
/// contents are generated or vendored.
const GENERATED_SEGMENTS: &[&str] = &[
    "/migrations/",
    "/obj/",
    "/bin/",
    "/node_modules/",
    "/.generated/",
];

/// Content markers (matched case-insensitively against the first ~1KB of
/// the file) that mark a file as generated. Standard headers emitted by
/// codegen tools across ecosystems.
const GENERATED_HEAD_MARKERS: &[&str] = &[
    "<auto-generated", // covers `// <auto-generated>` and `/// <auto-generated />`
    "this code was generated", // classic .NET codegen banner
    "[generatedcode",  // [GeneratedCode(...)] attribute
    "[compilergenerated", // [CompilerGenerated] attribute
    "do not edit",
    "code generated by", // Go convention: `// Code generated by ... DO NOT EDIT.`
    "@generated",        // Facebook/Meta and protobuf convention
];

/// Maximum number of bytes of `head` inspected for content markers.
const HEAD_SCAN_LIMIT: usize = 1024;

/// Returns true when the file at `rel_path` is machine generated.
///
/// `rel_path` is the repository-relative path (either separator accepted);
/// `head` is the first ~1KB of the file's content (more is tolerated but
/// only the first [`HEAD_SCAN_LIMIT`] bytes are inspected).
pub fn is_generated(rel_path: &str, head: &str) -> bool {
    path_is_generated(rel_path) || head_is_generated(head)
}

fn path_is_generated(rel_path: &str) -> bool {
    // Normalize: backslashes to slashes, lowercase, and a leading slash so
    // segment checks also match at the start of a relative path.
    let normalized: String = rel_path
        .chars()
        .map(|c| {
            if c == '\\' {
                '/'
            } else {
                c.to_ascii_lowercase()
            }
        })
        .collect();
    let slashed = format!("/{}", normalized.trim_start_matches('/'));

    if GENERATED_SEGMENTS.iter().any(|seg| slashed.contains(seg)) {
        return true;
    }
    if GENERATED_SUFFIXES.iter().any(|suf| slashed.ends_with(suf)) {
        return true;
    }
    let file_name = slashed.rsplit('/').next().unwrap_or("");
    GENERATED_FILENAMES
        .iter()
        .any(|name| file_name == *name || file_name.ends_with(&format!(".{name}")))
}

fn head_is_generated(head: &str) -> bool {
    // Clamp to the scan limit on a char boundary, then lowercase once.
    let mut end = head.len().min(HEAD_SCAN_LIMIT);
    while end < head.len() && !head.is_char_boundary(end) {
        end += 1;
    }
    let scan = head[..end].to_ascii_lowercase();
    GENERATED_HEAD_MARKERS
        .iter()
        .any(|marker| scan.contains(marker))
}

/// Partition of a file set into generated and human-written paths.
pub struct GeneratedReport {
    /// Paths classified as generated, sorted.
    pub generated: Vec<String>,
    /// Paths classified as human-written, sorted.
    pub human: Vec<String>,
}

/// Partitions `(rel_path, head)` pairs into generated vs. human-written.
/// Classification walks the input in order; each output vector is sorted
/// for deterministic reporting.
pub fn partition(files: &[(String, String)]) -> GeneratedReport {
    let mut generated = Vec::new();
    let mut human = Vec::new();
    for (path, head) in files {
        if is_generated(path, head) {
            generated.push(path.clone());
        } else {
            human.push(path.clone());
        }
    }
    generated.sort();
    human.sort();
    GeneratedReport { generated, human }
}

/// One-line summary for the brief, e.g.
/// `generated code: 41 file(s) excluded from architecture signal (migrations, protos, designers)`.
pub fn summary_line(report: &GeneratedReport) -> String {
    format!(
        "generated code: {} file(s) excluded from architecture signal (migrations, protos, designers)",
        report.generated.len()
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    fn gen(path: &str) -> bool {
        is_generated(path, "")
    }

    // --- path suffix family ---

    #[test]
    fn designer_files_are_generated() {
        assert!(gen(
            "src/Ordering.Infrastructure/Migrations/20230925_Initial.Designer.cs"
        ));
        assert!(gen("src/App/Form1.designer.cs")); // case-insensitive
    }

    #[test]
    fn xaml_and_source_generator_output_is_generated() {
        assert!(gen("obj-free/App.g.cs"));
        assert!(gen("src/App/MainWindow.g.i.cs"));
        assert!(gen("src/Api/Endpoints.Generated.cs"));
    }

    #[test]
    fn specflow_feature_codegen_is_generated() {
        assert!(gen("tests/Features/Checkout.feature.cs"));
    }

    #[test]
    fn proto_and_grpc_output_is_generated() {
        assert!(gen("src/ClientApp/Services/Basket/Protos/BasketGrpc.cs"));
        assert!(gen("src/Api/Protos/Basket.pb.cs"));
        assert!(gen("internal/api/basket.pb.go"));
        assert!(gen("client/basket_pb2.py"));
    }

    #[test]
    fn assembly_info_is_generated() {
        assert!(gen("Properties/AssemblyInfo.cs"));
        assert!(gen("obj-free/Catalog.API.AssemblyInfo.cs"));
    }

    // --- path segment family ---

    #[test]
    fn generated_directory_segments_are_flagged() {
        assert!(gen(
            "src/Ordering.Infrastructure/Migrations/OrderingContextModelSnapshot.cs"
        ));
        assert!(gen(
            "src/Catalog.API/obj/Debug/net8.0/Catalog.API.GlobalUsings.g.cs"
        ));
        assert!(gen("src/Catalog.API/bin/Release/helper.cs"));
        assert!(gen("web/node_modules/lodash/index.js"));
        assert!(gen("src/.generated/schema.ts"));
        // Segment match also works with Windows separators and at path start.
        assert!(gen(r"src\Ordering.Infrastructure\Migrations\Snapshot.cs"));
        assert!(gen("obj/Debug/AssemblyAttributes.cs"));
    }

    #[test]
    fn segment_must_be_a_whole_directory_name() {
        // "binary" and "migrations_notes" are not the /bin/ or /migrations/ dirs.
        assert!(!gen("src/binary/Parser.cs"));
        assert!(!gen("docs/migrations_notes/Plan.cs"));
        assert!(!gen("src/Orbiter/Cabinet.cs"));
    }

    // --- content head family ---

    #[test]
    fn auto_generated_header_is_flagged() {
        assert!(is_generated(
            "src/Api/Basket.cs",
            "// <auto-generated>\n//   by protoc\n"
        ));
        assert!(is_generated(
            "src/Api/Basket.cs",
            "\u{feff}// <AUTO-GENERATED />\nusing System;"
        ));
    }

    #[test]
    fn codegen_banners_are_flagged() {
        assert!(is_generated(
            "a.cs",
            "// This code was generated by a tool.\n"
        ));
        assert!(is_generated(
            "a.cs",
            "[GeneratedCode(\"protoc\", \"3.0\")]\nclass X {}"
        ));
        assert!(is_generated(
            "a.cs",
            "[CompilerGenerated]\ninternal class X {}"
        ));
        assert!(is_generated(
            "a.go",
            "// Code generated by protoc-gen-go. DO NOT EDIT.\n"
        ));
        assert!(is_generated("a.py", "# @generated by protobuf compiler\n"));
        assert!(is_generated(
            "a.ts",
            "/* DO NOT EDIT: regenerate with npm run codegen */"
        ));
    }

    #[test]
    fn markers_beyond_head_scan_limit_are_ignored() {
        let mut head = " ".repeat(HEAD_SCAN_LIMIT);
        head.push_str("// <auto-generated>");
        assert!(!is_generated("a.cs", &head));
    }

    #[test]
    fn head_clamp_respects_char_boundaries() {
        // A multi-byte char straddling the limit must not panic.
        let mut head = "x".repeat(HEAD_SCAN_LIMIT - 1);
        head.push('\u{00e9}'); // 2-byte char starting at limit-1
        head.push_str("tail");
        assert!(!is_generated("a.cs", &head));
    }

    // --- negatives: hand-written files must not be flagged ---

    #[test]
    fn hand_written_files_are_not_generated() {
        let order_head = "namespace eShop.Ordering.Domain.AggregatesModel.OrderAggregate;\n\npublic class Order : Entity, IAggregateRoot\n{\n";
        assert!(!is_generated(
            "src/Ordering.Domain/AggregatesModel/OrderAggregate/Order.cs",
            order_head
        ));
        let api_head =
            "using Microsoft.AspNetCore.Http.HttpResults;\n\npublic static class CatalogApi\n{\n";
        assert!(!is_generated(
            "src/Catalog.API/Apis/CatalogApi.cs",
            api_head
        ));
        // Names that merely resemble generated conventions.
        assert!(!gen("src/App/Designer.Tools.cs")); // not *.Designer.cs
        assert!(!gen("src/Info/AssemblyInfoReader.cs")); // not AssemblyInfo.cs
        assert!(!gen("src/Api/GrpcSettings.cs")); // Grpc not at end
        assert!(!is_generated(
            "src/Api/Program.cs",
            "// Startup wiring. Generated ideas welcome.\n"
        ));
    }

    // --- partition + summary ---

    #[test]
    fn partition_classifies_and_sorts() {
        let files = vec![
            (
                "src/Z/Order.cs".to_string(),
                "public class Order {}".to_string(),
            ),
            ("src/Migrations/X.Designer.cs".to_string(), String::new()),
            (
                "src/A/Basket.cs".to_string(),
                "// <auto-generated>".to_string(),
            ),
            (
                "src/A/Catalog.cs".to_string(),
                "public class Catalog {}".to_string(),
            ),
        ];
        let report = partition(&files);
        assert_eq!(
            report.generated,
            vec![
                "src/A/Basket.cs".to_string(),
                "src/Migrations/X.Designer.cs".to_string()
            ]
        );
        assert_eq!(
            report.human,
            vec!["src/A/Catalog.cs".to_string(), "src/Z/Order.cs".to_string()]
        );
    }

    #[test]
    fn summary_line_reports_count() {
        let report = GeneratedReport {
            generated: (0..41).map(|i| format!("f{i}.g.cs")).collect(),
            human: vec![],
        };
        assert_eq!(
            summary_line(&report),
            "generated code: 41 file(s) excluded from architecture signal (migrations, protos, designers)"
        );
    }

    // --- integration: real eShop checkout, skipped when absent ---

    #[test]
    fn eshop_real_files_classify_correctly() {
        let root = std::path::Path::new(
            "/private/tmp/claude-501/-Users-jag/e05fd682-3a3e-4c4f-8cb7-f66d17e5c3ac/scratchpad/eShop",
        );
        if !root.is_dir() {
            eprintln!("eShop fixture not present; skipping integration test");
            return;
        }

        let head_of = |rel: &str| -> String {
            let bytes = std::fs::read(root.join(rel)).unwrap_or_else(|e| panic!("read {rel}: {e}"));
            let take = bytes.len().min(1024);
            String::from_utf8_lossy(&bytes[..take]).into_owned()
        };

        // Every EF Core migration file must be flagged generated.
        let migrations_dir = root.join("src/Ordering.Infrastructure/Migrations");
        let mut checked = 0;
        for entry in std::fs::read_dir(&migrations_dir).expect("read Migrations dir") {
            let entry = entry.expect("dir entry");
            if !entry.file_type().map(|t| t.is_file()).unwrap_or(false) {
                continue;
            }
            let rel = format!(
                "src/Ordering.Infrastructure/Migrations/{}",
                entry.file_name().to_string_lossy()
            );
            assert!(
                is_generated(&rel, &head_of(&rel)),
                "expected generated: {rel}"
            );
            checked += 1;
        }
        assert!(checked > 0, "no migration files found");

        // Generated proto message output.
        let basket = "src/ClientApp/Services/Basket/Protos/Basket.cs";
        assert!(
            is_generated(basket, &head_of(basket)),
            "expected generated: {basket}"
        );

        // Hand-written domain and API code must NOT be flagged.
        for rel in [
            "src/Ordering.Domain/AggregatesModel/OrderAggregate/Order.cs",
            "src/Catalog.API/Apis/CatalogApi.cs",
        ] {
            assert!(
                !is_generated(rel, &head_of(rel)),
                "false positive on hand-written file: {rel}"
            );
        }
    }
}
