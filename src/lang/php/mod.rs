//! PHP front end: lossless lexer + CST parser + lowering, wired to the shared IR
//! through the [`LanguageFrontEnd`] seam.
//!
//! PHP is a *templating* language: a file is verbatim HTML until a `<?php` (or
//! `<?=` / `<?`) open tag, and returns to markup at a `?>` close tag. The lexer
//! stays purely lossless — markup outside `<?php … ?>` is preserved as
//! `inline_html` tokens, and the open/close tags as their own tokens — so the
//! parser and lowering only ever read real bytes. The lowering maps
//! `function`→`Function`, `class`/`interface`/`trait`/`enum`→`Type` (with the apt
//! `type_kind`), `namespace`→`Module`, `const`/`define`→`Constant`,
//! `extends`→`EXTENDS`, `implements`→`IMPLEMENTS`, `use Ns\X`→`IMPORTS`, and reuses
//! a deterministic scope-resolution ladder for `CALLS`.
//!
//! Namespaces are declared *in source* (`namespace App\Models;`), not derived from
//! the file path, so [`module_path`](LanguageFrontEnd::module_path) keeps the flat
//! default and the lowering reads the declared namespace instead.

pub mod lexer;
pub mod lower;
pub mod parser;

use crate::graph::Graph;
use crate::lang::frontend::{LanguageFrontEnd, LoweredInput};

/// The PHP language front end. Zero-sized: all state lives in the parse trees and
/// the lowering pass.
pub struct PhpFrontEnd;

impl LanguageFrontEnd for PhpFrontEnd {
    fn name(&self) -> &'static str {
        "php"
    }

    fn extensions(&self) -> &'static [&'static str] {
        &["php", "phtml"]
    }

    fn parse(&self, path: &str, source: &str) -> crate::core::cst::ParseTree {
        parser::parse(path, source)
    }

    fn lower(&self, input: &LoweredInput, graph: &mut Graph) {
        // The whole-project lowering produces a self-contained sub-graph (it needs
        // every file at once for the resolution ladder); merge it into the shared
        // graph the pipeline owns.
        let sub = lower::lower(input.package, &input.files, input.manifest_deps);
        graph.merge(sub);
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::lang::frontend::SourceFile;

    #[test]
    fn front_end_identity() {
        let fe = PhpFrontEnd;
        assert_eq!(fe.name(), "php");
        assert_eq!(fe.extensions(), &["php", "phtml"]);
    }

    /// The substrate's headline guarantee, exercised end-to-end on a representative
    /// PHP file: lex + parse must reconstruct the source byte-for-byte.
    #[test]
    fn lossless_round_trip_on_representative_source() {
        let src = "\
<?php
declare(strict_types=1);

namespace App\\Geo;

use App\\Contracts\\Saveable;
use Vendor\\Math\\{Vec2, Vec3};
require_once __DIR__ . '/helpers.php';

const TAU = 6.283_185;
define('APP', 'trailtracker');

#[Entity(table: 'points')]
abstract class Point implements Saveable
{
    use Loggable;

    public function __construct(
        public readonly float $x = 0.0,
        public readonly float $y = 0.0,
    ) {}

    public function label(): string
    {
        // interpolation + heredoc + nowdoc
        $name = \"({$this->x}, {$this->y})\";
        $doc = <<<TXT
        point $name
        TXT;
        $raw = <<<'RAW'
        literal $name
        RAW;
        return $name . $doc . $raw;
    }

    public function norm(): float
    {
        return sqrt($this->x ** 2 + $this->y ** 2);
    }
}

function build(float $x): Point
{
    return new Point($x, $x);
}
?>
<footer>generated by <?= APP ?></footer>
";
        let fe = PhpFrontEnd;
        let tree = fe.parse("src/Geo/Point.php", src);
        assert!(
            tree.is_lossless(),
            "PHP front end must reconstruct source byte-for-byte"
        );

        // And the batch lowers into the shared IR without panicking, producing the
        // expected core node kinds.
        let mut graph = Graph::new();
        let file = SourceFile {
            rel_path: "src/Geo/Point.php".to_string(),
            module_path: Vec::new(),
            source: &tree.source,
            root: &tree.root,
        };
        let input = LoweredInput {
            package: "trailtracker",
            manifest_deps: &[],
            files: vec![file],
        };
        fe.lower(&input, &mut graph);
        use crate::ir::ontology::node as ont;
        assert!(graph.count_nodes_of(ont::TYPE) >= 1);
        assert!(graph.count_nodes_of(ont::FUNCTION) >= 1);
        assert!(graph.count_nodes_of(ont::CONSTANT) >= 1);
    }
}
